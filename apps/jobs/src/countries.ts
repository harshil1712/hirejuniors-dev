// The name→code map is derived at module load from Intl.DisplayNames so it
// can't drift from the display names the site renders; filtering to the
// ALPHA3 map's ISO code set drops Intl's legacy aliases (UK, DD, SU, …).
// Hand aliases cover the short forms Intl doesn't emit.

const NAMES = new Intl.DisplayNames(["en"], { type: "region" });
const ISO_ALPHA2 = new Set(ALPHA3_TO_ALPHA2.values());

/** Every ISO alpha-2 Intl.DisplayNames can name (skips unassigned
 * "Unknown Region" answers and legacy alias codes). */
export const ALPHA2_CODES: readonly string[] = (() => {
  const codes: string[] = [];
  for (let a = 65; a <= 90; a++)
    for (let b = 65; b <= 90; b++) {
      const code = String.fromCharCode(a, b);
      const name = NAMES.of(code);
      if (name && name !== code && name !== "Unknown Region" && ISO_ALPHA2.has(code))
        codes.push(code);
    }
  return codes;
})();

export const COUNTRY_NAME_TO_ALPHA2 = new Map<string, string>([
  ...ALPHA2_CODES.map((code) => [NAMES.of(code)!.toUpperCase(), code] as [string, string]),
  // Aliases Intl doesn't emit.
  ["UK", "GB"],
  ["USA", "US"],
  ["UNITED STATES OF AMERICA", "US"],
  ["ENGLAND", "GB"],
  ["HONG KONG", "HK"],
]);
